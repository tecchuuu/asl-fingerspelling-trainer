import { useEffect, useState } from "react";

const pct = (x) => `${Math.round(x * 100)}%`;
const NEEDS_HELP = { mastered: 18, exam: 0.7 }; // flagged below either

/**
 * Trainer dashboard for an instructor. The class is SIMULATED (scripts/simulate_cohort.py):
 * labelled as such everywhere. Charts: one series each, one colour; no dual axes.
 */
export default function TrainerPage() {
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);
  const [groupSize, setGroupSize] = useState(10);
  const [hourCost, setHourCost] = useState(400);
  const [showTable, setShowTable] = useState(false);

  useEffect(() => {
    fetch("/api/trainer")
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(`HTTP ${r.status}`))))
      .then(setData)
      .catch((err) => setError(err.message));
  }, []);

  if (error) return <div className="page"><p className="bad">Couldn't load the trainer data: {error}</p></div>;
  if (!data) return <div className="page"><p className="muted">Loading...</p></div>;

  const { cohort, real } = data;
  const s = cohort.summary;
  const a = cohort.assumptions;
  const [minM, medM, maxM] = s.letters_mastered_min_median_max;
  const stuck = [...cohort.letters].sort((x, y) => x.learners_mastered - y.learners_mastered).slice(0, 8);
  const flagged = cohort.learners.filter(
    (l) => l.letters_mastered < NEEDS_HELP.mastered || l.weekly.at(-1).exam_score < NEEDS_HELP.exam,
  );
  const instructorHours = s.total_practice_hours / Math.max(groupSize, 1);

  return (
    <div className="page">
      <h1>Trainer dashboard</h1>
      <div className="sim-banner">
        <b>This class is simulated.</b> {s.learners} learners over {a.weeks} weeks, generated by a model of learner
        behaviour. Not real users. Letter recognition rates are measured from the real app.
        <details>
          <summary>How it's simulated</summary>
          <ul className="small">
            <li>Each learner has a skill level and practises {a.sessions_per_week_range[0]}–{a.sessions_per_week_range[1]} sessions a week, {a.letters_per_session_range[0]}–{a.letters_per_session_range[1]} letters per session.</li>
            <li>A sign counts if the learner forms the right shape <i>and</i> the app recognises it. Recognition per letter is measured on my webcam test ({cohort.model_acceptance.source}).</li>
            <li>Beginner shape accuracy is an assumption: easy {pct(a.shape_start_prob.easy)}, medium {pct(a.shape_start_prob.medium)}, hard {pct(a.shape_start_prob.hard)} (hard = closed fists and sideways/downward letters); it improves with every attempt.</li>
            <li>Mastered = {a.mastery}. Weekly exam: {a.exam_words} words, first try counts, {a.exam_max_misses} misses per letter.</li>
          </ul>
        </details>
      </div>

      <div className="tiles">
        <div className="tile"><div className="tile-value">{s.learners}</div><div className="tile-label">learners (simulated)</div></div>
        <div className="tile"><div className="tile-value">{medM}/24</div><div className="tile-label">letters mastered, median (range {minM}–{maxM})</div></div>
        <div className="tile"><div className="tile-value">{pct(s.weekly_exam_mean[0])} → {pct(s.weekly_exam_mean.at(-1))}</div><div className="tile-label">average exam score, week 1 to {a.weeks}</div></div>
        <div className="tile"><div className="tile-value">{s.total_practice_hours} h</div><div className="tile-label">practice time in the app</div></div>
      </div>

      <div className="two-col">
        <div className="panel">
          <h2>Where the class gets stuck</h2>
          <p className="muted small">Learners who mastered each letter (of {s.learners}), the 8 lowest. The note says why.</p>
          <StuckBars letters={stuck} total={s.learners} />
        </div>
        <div className="panel">
          <h2>Class progress by week</h2>
          <MiniLine title="Letters mastered (average)" values={s.weekly_mastered_mean} max={24} format={(v) => v.toFixed(1)} />
          <MiniLine title="Exam score (average)" values={s.weekly_exam_mean} max={1} format={pct} />
        </div>
      </div>

      <div className="panel">
        <h2>Instructor time saved (estimate)</h2>
        <p className="small muted">
          Drilling the alphabet is done in groups: one instructor hour covers a whole group.
          So app practice replaces <b>practice hours ÷ group size</b> instructor hours. Both inputs are assumptions; change them.
        </p>
        <div className="assumptions">
          <label>Group size <input type="number" min="1" max="50" value={groupSize} onChange={(e) => setGroupSize(Number(e.target.value) || 1)} /></label>
          <label>Instructor cost per hour (฿) <input type="number" min="0" step="50" value={hourCost} onChange={(e) => setHourCost(Number(e.target.value) || 0)} /></label>
        </div>
        <p className="saved">
          <b>{instructorHours.toFixed(1)} instructor hours</b> over {a.weeks} weeks
          {hourCost > 0 && <> ≈ <b>฿{Math.round(instructorHours * hourCost).toLocaleString()}</b></>}
          <span className="muted small"> ({s.total_practice_hours} h ÷ {groupSize}; simulated class)</span>
        </p>
      </div>

      <div className="panel">
        <div className="panel-head">
          <h2>Learners {flagged.length > 0 && <span className="status-tag">⚠ {flagged.length} need help</span>}</h2>
          <button className="ghost" onClick={() => setShowTable(!showTable)}>{showTable ? "Hide" : "Show"} all {s.learners}</button>
        </div>
        <p className="small muted">Needs help = fewer than {NEEDS_HELP.mastered} letters mastered or last exam under {pct(NEEDS_HELP.exam)}.</p>
        <table>
          <thead><tr><th>Learner (simulated)</th><th>Sessions/week</th><th>Practice</th><th>Mastered</th><th>Last exam</th><th>Status</th></tr></thead>
          <tbody>
            {(showTable ? cohort.learners : flagged).map((l) => {
              const help = flagged.includes(l);
              return (
                <tr key={l.name}>
                  <td>{l.name}</td>
                  <td>{l.sessions_per_week}</td>
                  <td>{Math.round(l.practice_minutes)} min</td>
                  <td>{l.letters_mastered}/24</td>
                  <td>{pct(l.weekly.at(-1).exam_score)}</td>
                  <td>{help ? <span className="status-tag">⚠ needs help</span> : <span className="muted">on track</span>}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      <p className="muted small">
        Your own real practice: {real.attempts} letters signed{real.attempts > 0 && `, ${pct(real.accuracy)} correct`} (see My progress).
      </p>
    </div>
  );
}

/** Horizontal bars, one series: learners who mastered each letter. Cause noted beside each bar. */
function StuckBars({ letters, total }) {
  const [hover, setHover] = useState(null);
  const why = (l) => {
    if (l.learners_mastered >= total / 2) return "";
    if (l.model_acceptance < 0.7) return `app recognises it ${pct(l.model_acceptance)} of the time`;
    if (l.attempts_per_learner < 15) return `rarely practised (${l.attempts_per_learner} tries per learner)`;
    return `hard shape (${pct(l.first_try_accuracy)} right first try)`;
  };
  return (
    <div className="hbars" onMouseLeave={() => setHover(null)}>
      {letters.map((l) => (
        <div key={l.letter} className="hbar-row" onMouseEnter={() => setHover(l.letter)}>
          <span className="hbar-label">{l.letter}</span>
          <div className="hbar-track">
            <div className="hbar" style={{ width: `${(l.learners_mastered / total) * 100}%` }} />
          </div>
          <span className="hbar-value">{l.learners_mastered}</span>
          <span className="hbar-why small muted">{why(l)}</span>
          {hover === l.letter && (
            <div className="hbar-tip small">
              <b>{l.letter}</b>: mastered by {l.learners_mastered} of {total}, {pct(l.first_try_accuracy)} right first try,
              app recognises it {pct(l.model_acceptance)} of the time, {l.attempts_per_learner} tries per learner
            </div>
          )}
        </div>
      ))}
    </div>
  );
}

/** Small single-series line chart (one per measure, never two scales on one axis). */
function MiniLine({ title, values, max, format }) {
  const [hover, setHover] = useState(null);
  const W = 320, H = 110, PAD = { l: 8, r: 8, t: 14, b: 20 };
  const x = (i) => PAD.l + (i * (W - PAD.l - PAD.r)) / (values.length - 1);
  const y = (v) => PAD.t + (1 - v / max) * (H - PAD.t - PAD.b);
  const points = values.map((v, i) => `${x(i)},${y(v)}`).join(" ");
  return (
    <div className="miniline">
      <div className="small"><b>{title}</b>{hover != null && <span className="muted">, week {hover + 1}: {format(values[hover])}</span>}</div>
      <svg viewBox={`0 0 ${W} ${H}`} role="img" aria-label={`${title}: ${values.map(format).join(", ")}`}>
        <line x1={PAD.l} x2={W - PAD.r} y1={y(0)} y2={y(0)} className="axis" />
        <line x1={PAD.l} x2={W - PAD.r} y1={y(max)} y2={y(max)} className="gridline" />
        <polyline points={points} className="series-line" />
        {values.map((v, i) => (
          <g key={i} onMouseEnter={() => setHover(i)} onMouseLeave={() => setHover(null)}>
            <rect x={x(i) - 20} y={0} width={40} height={H} fill="transparent" />
            {hover === i && <line x1={x(i)} x2={x(i)} y1={PAD.t} y2={y(0)} className="crosshair" />}
            <circle cx={x(i)} cy={y(v)} r={hover === i ? 5 : 4} className="series-dot" />
            <text x={x(i)} y={H - 4} textAnchor="middle" className="tick">W{i + 1}</text>
            {(i === 0 || i === values.length - 1) && (
              <text x={x(i)} y={y(v) - 8} textAnchor={i === 0 ? "start" : "end"} className="point-label">{format(v)}</text>
            )}
          </g>
        ))}
      </svg>
    </div>
  );
}
